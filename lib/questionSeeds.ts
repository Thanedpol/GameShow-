function shuffle<T>(input: readonly T[]): T[] {
  const arr = [...input];
  for (let i = arr.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export interface QuestionSeed {
  domain: string;
  angle: string;
  skill: string;
}

/**
 * สุ่มบรีฟ n ชุดโดยไม่ให้โดเมนซ้ำกันภายในชุดเดียว
 *
 * โดเมนห้ามซ้ำเพราะเป็นตัวกำหนดว่าคำถามจะพูดถึงเรื่องอะไร ถ้าซ้ำผู้เล่นจะรู้สึกว่า
 * เกมถามเรื่องเดิมวนไปมา ส่วนมุมมองกับทักษะซ้ำได้ ผลลัพธ์ยังต่างกันพอ
 */
export function drawSeeds(n: number): QuestionSeed[] {
  const domains = shuffle(DOMAINS);
  const angles = shuffle(ANGLES);
  const skills = shuffle(SKILLS);
  return Array.from({ length: n }, (_, i) => ({
    domain: domains[i % domains.length],
    angle: angles[i % angles.length],
    skill: skills[i % skills.length],
  }));
}

export function drawPerformanceTasks(n: number): string[] {
  const tasks = shuffle(PERFORMANCE_TASKS);
  return Array.from({ length: n }, (_, i) => tasks[i % tasks.length]);
}
